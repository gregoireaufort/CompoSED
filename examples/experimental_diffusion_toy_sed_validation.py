def plot_inverse_summary(comparison: dict, output_dir: Path) -> None:
    import matplotlib.pyplot as plt

    names = PARAM_NAMES
    fig, axes = plt.subplots(1, 3, figsize=(13.5, 3.8))

    ax = axes[0]
    for j, name in enumerate(names):
        ax.scatter(comparison["reference_mean"][:, j], comparison["diffusion_mean"][:, j], s=15, alpha=0.65, label=name)
    lo = min(float(np.min(comparison["reference_mean"])), float(np.min(comparison["diffusion_mean"])))
    hi = max(float(np.max(comparison["reference_mean"])), float(np.max(comparison["diffusion_mean"])))
    ax.plot([lo, hi], [lo, hi], color="0.4", ls="--")
    ax.set_xlabel("MC reference posterior mean")
    ax.set_ylabel("diffusion posterior mean")
    ax.set_title("theta | all mags")
    ax.legend(fontsize=8)

    ax = axes[1]
    for j, name in enumerate(names):
        ax.hist(comparison["rank_percentiles"][:, j], bins=np.linspace(0.0, 1.0, 11), alpha=0.45, label=name)
    ax.set_xlabel("rank percentile of generating truth")
    ax.set_ylabel("count")
    ax.set_title("rank histogram")
    ax.legend(fontsize=8)

    ax = axes[2]
    curve = comparison["coverage_curve"]
    ax.plot([0.0, 1.0], [0.0, 1.0], color="0.4", ls="--", label="ideal")
    for j, name in enumerate(names):
        ax.plot(curve["levels"], curve["coverage"][:, j], marker="o", label=name)
    ax.set_xlabel("central credible level")
    ax.set_ylabel("empirical coverage")
    ax.set_xlim(0.0, 1.0)
    ax.set_ylim(0.0, 1.0)
    ax.set_title("coverage")
    ax.legend(fontsize=8)

    fig.tight_layout()
    fig.savefig(output_dir / "inverse_theta_given_mags_summary.png", dpi=160)
    plt.close(fig)


