def run_validation(
    *,
    n_train: int = 8192,
    n_test: int = 16,
    n_reference: int = 50_000,
    epochs: int = 90,
    num_samples: int = 128,
    steps: int = 32,
    seed: int = 20260706,
    output_dir: str | Path = "outputs/diffusion_toy_sed_validation",
    model: str = "mlp",
    strict: bool = False,
    verbose: bool = False,
) -> dict:
    """Run the nonlinear toy-SED diffusion validation."""

    output_path = Path(output_dir)
    output_path.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(seed)

    x_train, _, _ = make_training_table(rng, n_train)
    x_test, mags_test, theta_test = make_training_table(rng, n_test)
    reference_theta = sample_prior(rng, n_reference)
    reference_mags_noiseless = toy_noiseless_magnitudes(reference_theta)

    feature_names = BAND_NAMES + PARAM_NAMES
    metadata = FeatureMetadata.from_groups({"mags": BAND_NAMES, "params": PARAM_NAMES})
    if model == "hybrid_sed":
        model_config = {
            "emb_dim": 48,
            "time_hidden": 64,
            "cnn_channels": 32,
            "cnn_blocks": 1,
            "param_hidden": 64,
            "param_blocks": 1,
            "fusion_hidden": 64,
            "fusion_blocks": 2,
        }
    else:
        model_config = {
            "hidden_features": 96,
            "num_blocks": 3,
            "emb_dim": 64,
            "time_hidden": 96,
        }
    estimator = ConditionalDiffusionEstimator(
        metadata,
        model=model,
        hidden_features=96,
        model_config=model_config,
        sigma_min=0.02,
        sigma_max=2.0,
        learning_rate=2e-3,
        device="auto",
    )
    history = estimator.fit(
        x_train,
        mask_config={
            "curriculum": [
                {"weight": 1.0, "unknown_fraction": {"mags": 0.0, "params": 1.0}},
                {"weight": 1.0, "unknown_fraction": {"mags": 1.0, "params": 0.0}},
                {"weight": 1.0, "unknown_fraction": {"mags": [0.25, 0.5, 0.75], "params": [0.5, 1.0]}},
            ]
        },
        epochs=epochs,
        batch_size=1024,
        seed=seed,
        clamp_known_in_xt=True,
        loss_on_unknown_only=True,
        verbose=verbose,
    )

    all_mag_index = np.arange(len(BAND_NAMES))
    theta_index = np.arange(len(BAND_NAMES), len(feature_names))
    inverse_full, inverse_seconds, inverse_clamp = sample_diffusion_case(
        estimator,
        x_test,
        all_mag_index,
        num_samples=num_samples,
        steps=steps,
    )
    inverse_diffusion = inverse_full[:, :, theta_index]
    inverse_reference, inverse_ess = reference_inverse_samples(
        mags_test,
        reference_theta,
        reference_mags_noiseless,
        rng,
        n_samples=num_samples,
        band_index=all_mag_index,
    )
    inverse = compare_sample_cubes(inverse_diffusion, inverse_reference, theta_test)
    inverse["seconds"] = inverse_seconds
    inverse["known_max_abs_error"] = inverse_clamp

    forward = evaluate_forward_mags_given_theta(
        estimator,
        x_test,
        theta_test,
        num_samples=num_samples,
        steps=steps,
    )

    known_blue_index = np.array([0, 1, 2, 3], dtype=int)
    missing_red_index = np.array([4, 5, 6, 7], dtype=int)
    mixed_known_index = known_blue_index
    mixed_full, mixed_seconds, mixed_clamp = sample_diffusion_case(
        estimator,
        x_test,
        mixed_known_index,
        num_samples=num_samples,
        steps=steps,
    )
    mixed_unknown_index = np.concatenate([missing_red_index, theta_index])
    mixed_diffusion = mixed_full[:, :, mixed_unknown_index]
    mixed_reference, mixed_ess = reference_mixed_samples(
        mags_test,
        reference_theta,
        reference_mags_noiseless,
        rng,
        n_samples=num_samples,
        known_band_index=known_blue_index,
        missing_band_index=missing_red_index,
    )
    mixed_truth = np.column_stack([mags_test[:, missing_red_index], theta_test])
    mixed = compare_sample_cubes(mixed_diffusion, mixed_reference, mixed_truth)
    mixed["seconds"] = mixed_seconds
    mixed["known_max_abs_error"] = mixed_clamp
    mixed_unknown_names = [feature_names[i] for i in mixed_unknown_index]

    plot_training_loss(history, output_path)
    plot_inverse_summary(inverse, output_path)
    plot_forward_summary(forward, output_path)
    plot_mixed_summary(mixed, mixed_unknown_names, output_path)
    plot_toy_sed_example(mags_test[0], theta_test[0], inverse_diffusion, output_path)

    metrics = serializable_metrics(
        history=history,
        device=str(estimator.device),
        inverse=inverse,
        forward=forward,
        mixed=mixed,
        inverse_ess=inverse_ess,
        mixed_ess=mixed_ess,
        mixed_unknown_names=mixed_unknown_names,
    )
    metrics["model"] = str(model)
    metrics["n_train"] = int(n_train)
    metrics["n_test"] = int(n_test)
    metrics["n_reference"] = int(n_reference)
    metrics["num_samples"] = int(num_samples)
    metrics["steps"] = int(steps)
    metrics["strict"] = bool(strict)
    metrics["smoke_checks"] = {
        "finite_inverse_samples": bool(np.all(np.isfinite(inverse_diffusion))),
        "finite_mixed_samples": bool(np.all(np.isfinite(mixed_diffusion))),
        "known_coordinates_clamped": bool(max(inverse_clamp, forward["known_max_abs_error"], mixed_clamp) <= 1e-5),
        "inverse_reference_ess_ok": bool(np.median(inverse_ess) >= 25),
        "inverse_mean_error_ok": bool(np.mean(inverse["normalized_mean_abs_error"]) <= 2.0),
        "forward_mean_rmse_ok": bool(forward["mean_rmse"] <= 1.0),
    }
    metrics["inverse_theta_given_all_mags"]["seconds"] = float(inverse_seconds)
    metrics["inverse_theta_given_all_mags"]["known_max_abs_error"] = float(inverse_clamp)
    metrics["mixed_missing_red_bands"]["seconds"] = float(mixed_seconds)
    metrics["mixed_missing_red_bands"]["known_max_abs_error"] = float(mixed_clamp)

    with (output_path / "metrics.json").open("w", encoding="utf-8") as handle:
        json.dump(metrics, handle, indent=2)

    if max(inverse_clamp, forward["known_max_abs_error"], mixed_clamp) > 1e-5:
        raise RuntimeError("Known/clamped coordinates were not preserved exactly.")
    if not np.all(np.isfinite(inverse_diffusion)) or not np.all(np.isfinite(mixed_diffusion)):
        raise RuntimeError("Diffusion samples contain NaN or inf.")
    if strict:
        if np.median(inverse_ess) < 25:
            raise RuntimeError("Reference posterior ESS is too small; increase n_reference or noise.")
        if np.mean(inverse["normalized_mean_abs_error"]) > 2.0:
            raise RuntimeError("Inverse posterior differs too strongly from the brute-force reference.")
        if forward["mean_rmse"] > 1.0:
            raise RuntimeError("Forward sampled magnitudes are too far from the exact toy likelihood mean.")

    return metrics


