BAND_NAMES = ["u", "g", "r", "i", "z", "Y", "J", "H"]
BAND_WAVELENGTH_UM = np.array([0.36, 0.48, 0.62, 0.76, 0.90, 1.05, 1.25, 1.65])
PARAM_NAMES = ["redshift", "log10_mass", "dust2", "logzsol"]
PARAM_LOW = np.array([0.0, 8.0, 0.0, -1.2])
PARAM_HIGH = np.array([3.0, 12.0, 1.2, 0.3])
# This deliberately uses broad toy magnitude errors.  The purpose is to test
# the masked joint sampler against a brute-force reference posterior without
# making the validation dominated by a few extremely sharp nearest-neighbour
# points in the reference prior bank.
MAG_SIGMA = np.array([0.32, 0.28, 0.25, 0.23, 0.23, 0.25, 0.28, 0.32])


def sample_prior(rng: np.random.Generator, n: int) -> np.ndarray:
    """Draw toy physical parameters from independent uniform priors."""

    unit = rng.uniform(0.0, 1.0, size=(int(n), PARAM_LOW.size))
    return PARAM_LOW + unit * (PARAM_HIGH - PARAM_LOW)


def toy_noiseless_magnitudes(theta: np.ndarray) -> np.ndarray:
    """Return nonlinear toy observed magnitudes for ``theta``.

    Parameters are ordered as ``[redshift, log10_mass, dust2, logzsol]``.
    The model includes mass brightening, redshift dimming, a 4000 Angstrom-like
    break, a Lyman-like blue dropout, smooth dust reddening, metallicity color,
    and broad emission-line bumps.  The constants are chosen for diagnostic
    structure, not physical calibration.
    """

    theta = np.asarray(theta, dtype=float)
    if theta.ndim == 1:
        theta = theta[None, :]
    z = theta[:, 0:1]
    log10_mass = theta[:, 1:2]
    dust2 = theta[:, 2:3]
    logzsol = theta[:, 3:4]

    obs_um = BAND_WAVELENGTH_UM.reshape(1, -1)
    rest_um = obs_um / (1.0 + z)
    log_rest = np.log(rest_um / 0.55)

    mass_term = 23.4 - 2.35 * (log10_mass - 10.0)
    distance_like = 2.2 * np.log1p(z) + 0.8 * z
    continuum_color = 0.55 * log_rest + 0.18 * np.sin(2.5 * log_rest + 0.6 * z)
    dust_attenuation = 1.15 * dust2 * np.power(np.maximum(rest_um, 0.09) / 0.55, -0.75)

    break_strength = 0.45 + 0.35 * (logzsol + 0.6) + 0.20 * dust2
    blue_side_of_break = 1.0 / (1.0 + np.exp((rest_um - 0.40) / 0.035))
    break_term = break_strength * blue_side_of_break

    lyman_drop = 2.8 * (1.0 + 0.2 * z) / (1.0 + np.exp((rest_um - 0.1216) / 0.015))
    metallicity_color = 0.25 * logzsol * np.tanh((rest_um - 0.65) / 0.25)

    line_strength = (0.45 + 0.25 * np.tanh(log10_mass - 10.0)) * np.exp(-1.4 * dust2)
    line_term = np.zeros_like(rest_um)
    for line_um, amplitude, width_um in [(0.3727, 0.55, 0.035), (0.5007, 0.75, 0.045), (0.6563, 0.65, 0.055)]:
        line_term -= amplitude * line_strength * np.exp(-0.5 * ((rest_um - line_um) / width_um) ** 2)

    mags = mass_term + distance_like + continuum_color + dust_attenuation + break_term + lyman_drop + metallicity_color + line_term
    return np.asarray(mags, dtype=float)


def simulate_observed_magnitudes(theta: np.ndarray, rng: np.random.Generator) -> np.ndarray:
    noiseless = toy_noiseless_magnitudes(theta)
    return noiseless + rng.normal(0.0, MAG_SIGMA.reshape(1, -1), size=noiseless.shape)


def make_training_table(rng: np.random.Generator, n: int) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    theta = sample_prior(rng, n)
    mags = simulate_observed_magnitudes(theta, rng)
    return np.column_stack([mags, theta]), mags, theta


def log_mag_likelihood(observed_mags: np.ndarray, model_mags: np.ndarray, band_index: np.ndarray) -> np.ndarray:
    """Diagonal Gaussian magnitude likelihood up to an additive constant."""

    residual = (observed_mags[band_index] - model_mags[:, band_index]) / MAG_SIGMA[band_index]
    return -0.5 * np.sum(residual**2, axis=1)


def weighted_resample(
    values: np.ndarray,
    log_weight: np.ndarray,
    rng: np.random.Generator,
    n_samples: int,
) -> tuple[np.ndarray, np.ndarray, float]:
    """Resample rows from log weights and return effective sample size."""

    log_weight = np.asarray(log_weight, dtype=float)
    finite = np.isfinite(log_weight)
    if not np.any(finite):
        raise RuntimeError("All reference posterior log weights are non-finite.")
    shifted = log_weight - np.max(log_weight[finite])
    weight = np.exp(shifted)
    weight[~finite] = 0.0
    weight_sum = np.sum(weight)
    if weight_sum <= 0.0:
        raise RuntimeError("All reference posterior weights are zero.")
    probability = weight / weight_sum
    ess = 1.0 / np.sum(probability**2)
    index = rng.choice(values.shape[0], size=int(n_samples), replace=True, p=probability)
    return values[index], probability, float(ess)


def reference_inverse_samples(
    observed_mags: np.ndarray,
    reference_theta: np.ndarray,
    reference_mags_noiseless: np.ndarray,
    rng: np.random.Generator,
    *,
    n_samples: int,
    band_index: np.ndarray,
) -> tuple[np.ndarray, np.ndarray]:
    """Brute-force prior-bank posterior samples for theta | observed bands."""

    samples = []
    ess_values = []
    for row in range(observed_mags.shape[0]):
        logw = log_mag_likelihood(observed_mags[row], reference_mags_noiseless, band_index)
        ref, _, ess = weighted_resample(reference_theta, logw, rng, n_samples)
        samples.append(ref)
        ess_values.append(ess)
    return np.asarray(samples), np.asarray(ess_values)


def reference_mixed_samples(
    observed_mags: np.ndarray,
    reference_theta: np.ndarray,
    reference_mags_noiseless: np.ndarray,
    rng: np.random.Generator,
    *,
    n_samples: int,
    known_band_index: np.ndarray,
    missing_band_index: np.ndarray,
) -> tuple[np.ndarray, np.ndarray]:
    """Reference samples for [missing mags, theta] | known observed mags."""

    samples = []
    ess_values = []
    for row in range(observed_mags.shape[0]):
        logw = log_mag_likelihood(observed_mags[row], reference_mags_noiseless, known_band_index)
        theta_samples, probability, ess = weighted_resample(reference_theta, logw, rng, n_samples)
        chosen = rng.choice(reference_theta.shape[0], size=n_samples, replace=True, p=probability)
        missing_mean = reference_mags_noiseless[chosen][:, missing_band_index]
        missing_mags = missing_mean + rng.normal(0.0, MAG_SIGMA[missing_band_index], size=missing_mean.shape)
        samples.append(np.column_stack([missing_mags, theta_samples]))
        ess_values.append(ess)
    return np.asarray(samples), np.asarray(ess_values)


def sample_diffusion_case(
    estimator: ConditionalDiffusionEstimator,
    x_test: np.ndarray,
    known_index: np.ndarray,
    *,
    num_samples: int,
    steps: int,
) -> tuple[np.ndarray, float, float]:
    """Sample the diffusion conditional and return samples, seconds, clamp error."""

    known_index = np.asarray(known_index, dtype=int)
    mask = np.zeros_like(x_test, dtype=bool)
    mask[:, known_index] = True
    known = np.full_like(x_test, np.nan)
    known[:, known_index] = x_test[:, known_index]
    t0 = time.perf_counter()
    samples = estimator.sample(
        known,
        mask,
        num_samples=num_samples,
        steps=steps,
        sampler="edm_euler",
        batch_size=min(64, x_test.shape[0]),
    )
    seconds = time.perf_counter() - t0
    clamp_error = float(np.max(np.abs(samples[:, :, known_index] - x_test[:, None, known_index])))
    return samples, seconds, clamp_error


def compare_sample_cubes(diffusion_samples: np.ndarray, reference_samples: np.ndarray, truth: np.ndarray) -> dict:
    """Compare diffusion samples to reference samples and generating truth."""

    diff_mean = np.mean(diffusion_samples, axis=1)
    ref_mean = np.mean(reference_samples, axis=1)
    diff_std = np.std(diffusion_samples, axis=1)
    ref_std = np.std(reference_samples, axis=1)
    median = np.median(diffusion_samples, axis=1)
    normalized_mean_abs_error = np.mean(np.abs(diff_mean - ref_mean) / np.maximum(ref_std, 1e-6), axis=0)
    std_relative_error = np.mean(np.abs(diff_std - ref_std) / np.maximum(ref_std, 1e-6), axis=0)
    truth_rmse = np.sqrt(np.mean((median - truth) ** 2, axis=0))
    coverage_68 = central_interval_coverage(diffusion_samples, truth, level=0.68)
    ranks = rank_statistics(diffusion_samples, truth)
    coverage_curve = marginal_coverage(diffusion_samples, truth, levels=np.array([0.5, 0.68, 0.9]))
    return {
        "diffusion_mean": diff_mean,
        "reference_mean": ref_mean,
        "diffusion_std": diff_std,
        "reference_std": ref_std,
        "normalized_mean_abs_error": normalized_mean_abs_error,
        "std_relative_error": std_relative_error,
        "truth_rmse": truth_rmse,
        "coverage_68": coverage_68,
        "rank_percentiles": ranks["rank_percentiles"],
        "coverage_curve": coverage_curve,
    }


def central_interval_coverage(samples: np.ndarray, truth: np.ndarray, level: float = 0.68) -> np.ndarray:
    low_q = 0.5 * (1.0 - level)
    high_q = 1.0 - low_q
    lo = np.quantile(samples, low_q, axis=1)
    hi = np.quantile(samples, high_q, axis=1)
    return np.mean((truth >= lo) & (truth <= hi), axis=0)


def evaluate_forward_mags_given_theta(
    estimator: ConditionalDiffusionEstimator,
    x_test: np.ndarray,
    theta_test: np.ndarray,
    *,
    num_samples: int,
    steps: int,
) -> dict:
    """Evaluate sampled noisy magnitudes against exact p(mags | theta)."""

    known_index = np.arange(len(BAND_NAMES), len(BAND_NAMES) + len(PARAM_NAMES))
    samples, seconds, clamp_error = sample_diffusion_case(estimator, x_test, known_index, num_samples=num_samples, steps=steps)
    mag_samples = samples[:, :, : len(BAND_NAMES)]
    exact_mean = toy_noiseless_magnitudes(theta_test)
    exact_std = np.broadcast_to(MAG_SIGMA.reshape(1, -1), exact_mean.shape)
    sample_mean = np.mean(mag_samples, axis=1)
    sample_std = np.std(mag_samples, axis=1)
    return {
        "samples": mag_samples,
        "seconds": seconds,
        "known_max_abs_error": clamp_error,
        "mean_rmse": float(np.sqrt(np.mean((sample_mean - exact_mean) ** 2))),
        "std_relative_error": float(np.mean(np.abs(sample_std - exact_std) / exact_std)),
        "sample_mean": sample_mean,
        "exact_mean": exact_mean,
        "sample_std": sample_std,
        "exact_std": exact_std,
    }


