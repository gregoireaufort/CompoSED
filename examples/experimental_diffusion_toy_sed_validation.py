"""Nonlinear toy-SED validation for experimental diffusion SBI.

This is the second validation rung after the analytic Gaussian conditional
test.  The simulator is still intentionally simple and fast, but it has the
shape of an SED problem:

    theta = [redshift, log10_mass, dust2, logzsol]
    x     = [u, g, r, i, z, Y, J, H magnitudes, theta]

The photometry is generated by a deterministic nonlinear toy SED plus Gaussian
mag noise.  Because the prior and noise model are explicit, we can compare the
diffusion posterior against a brute-force Monte Carlo reference posterior.

This is not a physical FSPS/CIGALE validation.  It checks whether masked
diffusion can learn SED-like nonlinear inverse, forward, and missing-band
conditionals before expensive backend physics enters the loop.
"""

