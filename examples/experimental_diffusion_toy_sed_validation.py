def plot_toy_sed_example(
    observed_mags: np.ndarray,
    theta: np.ndarray,
    inverse_samples: np.ndarray,
    output_dir: Path,
) -> None:
    import matplotlib.pyplot as plt

    true_noiseless = toy_noiseless_magnitudes(theta[None, :])[0]
    posterior_theta = inverse_samples[0]
    idx = np.linspace(0, posterior_theta.shape[0] - 1, min(80, posterior_theta.shape[0]), dtype=int)
    posterior_mags = toy_noiseless_magnitudes(posterior_theta[idx])
    q16, q50, q84 = np.quantile(posterior_mags, [0.16, 0.5, 0.84], axis=0)

    fig, ax = plt.subplots(figsize=(7.0, 4.2))
    ax.errorbar(BAND_WAVELENGTH_UM, observed_mags, yerr=MAG_SIGMA, fmt="o", color="k", label="observed noisy mags")
    ax.plot(BAND_WAVELENGTH_UM, true_noiseless, color="C0", lw=2, label="true noiseless toy SED")
    ax.plot(BAND_WAVELENGTH_UM, q50, color="C3", lw=2, label="diffusion posterior median SED")
    ax.fill_between(BAND_WAVELENGTH_UM, q16, q84, color="C3", alpha=0.22, label="16-84%")
    ax.invert_yaxis()
    ax.set_xscale("log")
    ax.set_xticks(BAND_WAVELENGTH_UM, BAND_NAMES)
    ax.set_xlabel("observed band")
    ax.set_ylabel("magnitude")
    ax.set_title("Toy SED posterior predictive example")
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(output_dir / "toy_sed_posterior_predictive_example.png", dpi=160)
    plt.close(fig)


